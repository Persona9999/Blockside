"""Pack original town category PNGs into the single-file game. Run with --check to verify."""
import argparse
import base64
import json
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent
ART = ROOT / 'art' / 'townbuild'
OUT = ROOT / 'js' / '87_townbuild_art.js'


def pack():
    cats = json.loads((ART / 'categories.json').read_text(encoding='utf-8'))
    result = {}
    for c in cats:
        p = ART / (c['key'] + '.png')
        with Image.open(p) as im:
            if im.size != (128, 128) or im.mode != 'RGBA':
                raise ValueError(str(p) + ': expected 128x128 RGBA')
            a = im.getchannel('A')
            if a.getextrema() != (0, 255) or not a.getbbox():
                raise ValueError(str(p) + ': missing transparent background or opaque subject')
        result[c['key']] = {'name': c['name'], 'src': 'data:image/png;base64,' + base64.b64encode(p.read_bytes()).decode('ascii')}
    return '// Generated by src/townbuild_art.py; edit src/art/townbuild sources.\nvar TWB_CATEGORY_ART = ' + json.dumps(result, ensure_ascii=False, separators=(',', ':')) + ';\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = pack()
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding='utf-8') != content:
            raise SystemExit('Category icon bundle is stale; run python src/townbuild_art.py')
        print('Category icon bundle matches all source PNGs')
    else:
        OUT.write_text(content, encoding='utf-8', newline='\n')
        print('Packed category icons:', len(json.loads((ART / 'categories.json').read_text(encoding='utf-8'))))
